CREATE TABLE payment_order (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 org_id BIGINT NOT NULL, order_id BIGINT NOT NULL REFERENCES customer_order(id), customer_id BIGINT NOT NULL,
 channel TEXT NOT NULL CHECK(channel IN ('MOCK','WECHAT')),
 out_trade_no VARCHAR(32) NOT NULL UNIQUE, transaction_id TEXT UNIQUE,
 amount BIGINT NOT NULL CHECK(amount > 0), currency TEXT NOT NULL DEFAULT 'CNY' CHECK(currency='CNY'),
 status TEXT NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','SUCCESS','CLOSED','FAILED')),
 expires_at TIMESTAMPTZ NOT NULL, paid_at TIMESTAMPTZ,
 prepay_id TEXT, prepay_lease_until TIMESTAMPTZ,
 next_check_at TIMESTAMPTZ NOT NULL DEFAULT now(), check_count INTEGER NOT NULL DEFAULT 0,
 last_error TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX payment_one_active ON payment_order(order_id) WHERE status IN ('PENDING','SUCCESS');
CREATE INDEX payment_pending ON payment_order(next_check_at) WHERE status='PENDING';
CREATE TABLE payment_refund (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 org_id BIGINT NOT NULL, payment_id BIGINT NOT NULL REFERENCES payment_order(id),
 out_refund_no VARCHAR(32) NOT NULL UNIQUE, refund_id TEXT UNIQUE,
 amount BIGINT NOT NULL CHECK(amount > 0), reason VARCHAR(512) NOT NULL,
 status TEXT NOT NULL DEFAULT 'PROCESSING' CHECK(status IN ('PROCESSING','SUCCESS','ABNORMAL','CLOSED')),
 operator_id BIGINT NOT NULL, idempotency_key VARCHAR(128) NOT NULL,
 next_check_at TIMESTAMPTZ NOT NULL DEFAULT now(), check_count INTEGER NOT NULL DEFAULT 0, last_error TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), completed_at TIMESTAMPTZ,
 UNIQUE(org_id,idempotency_key)
);
CREATE INDEX payment_refund_pending ON payment_refund(next_check_at) WHERE status='PROCESSING';
CREATE TABLE payment_event (
 event_key TEXT PRIMARY KEY, channel TEXT NOT NULL, payload_hash BYTEA NOT NULL,
 processed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
