ALTER TABLE customer_order ADD COLUMN demand_version INTEGER NOT NULL DEFAULT 0 CHECK(demand_version >= 0);
CREATE TABLE order_demand_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 org_id BIGINT NOT NULL, order_id BIGINT NOT NULL REFERENCES customer_order(id) ON DELETE CASCADE,
 customer_id BIGINT NOT NULL, demand_version INTEGER NOT NULL,
 before_json JSONB NOT NULL, after_json JSONB NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), UNIQUE(org_id,order_id,demand_version)
);
CREATE TABLE order_demand_history_media (
 history_id BIGINT NOT NULL REFERENCES order_demand_history(id) ON DELETE CASCADE,
 media_id BIGINT NOT NULL REFERENCES media_asset(id), PRIMARY KEY(history_id,media_id)
);
CREATE INDEX order_demand_history_media_asset ON order_demand_history_media(media_id);
