ALTER TABLE customer ADD COLUMN status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','DISABLED')),
 ADD COLUMN last_login_at TIMESTAMPTZ, ADD COLUMN last_activity_at TIMESTAMPTZ,
 ADD COLUMN mobile_verified_at TIMESTAMPTZ, ADD COLUMN avatar_media_id BIGINT REFERENCES media_asset(id),
 ADD CONSTRAINT uk_customer_org_id UNIQUE(org_id,id),
 ADD CONSTRAINT ck_customer_mobile_required CHECK(mobile_cipher IS NOT NULL AND mobile_hash IS NOT NULL) NOT VALID;
CREATE UNIQUE INDEX uk_customer_mobile ON customer(org_id,mobile_hash);
CREATE INDEX idx_customer_activity ON customer(org_id,last_activity_at DESC);
CREATE TABLE customer_wechat_identity (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, org_id BIGINT NOT NULL, customer_id BIGINT NOT NULL,
 appid VARCHAR(64) NOT NULL, openid VARCHAR(128) NOT NULL, unionid VARCHAR(128),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(org_id,customer_id,appid,openid), FOREIGN KEY(org_id,customer_id) REFERENCES customer(org_id,id)
);
CREATE TABLE customer_session (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, org_id BIGINT NOT NULL, customer_id BIGINT NOT NULL,
 appid VARCHAR(64) NOT NULL, openid VARCHAR(128) NOT NULL,
 token_hash BYTEA NOT NULL UNIQUE CHECK(octet_length(token_hash)=32),
 expires_at TIMESTAMPTZ NOT NULL, revoked_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 FOREIGN KEY(org_id,customer_id) REFERENCES customer(org_id,id)
);
CREATE INDEX idx_customer_session_owner ON customer_session(org_id,customer_id,expires_at);
CREATE TABLE customer_initialization (
 name TEXT PRIMARY KEY, completed_at TIMESTAMPTZ NOT NULL DEFAULT now(), media_objects JSONB NOT NULL DEFAULT '[]'
);
